CREATE TABLE measurement_units (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 symbol VARCHAR(50) NOT NULL CHECK (LENGTH(BTRIM(symbol)) > 0),
 name VARCHAR(150),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_measurement_units_symbol ON measurement_units(LOWER(BTRIM(symbol)));
