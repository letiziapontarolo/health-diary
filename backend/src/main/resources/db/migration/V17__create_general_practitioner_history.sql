CREATE TABLE user_general_practitioners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    doctor_id BIGINT NOT NULL,
    start_date DATE,
    end_date DATE,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (doctor_id, user_id) REFERENCES doctors(id, user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_gp_dates CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date),
    CONSTRAINT chk_gp_current_end CHECK (NOT is_current OR end_date IS NULL)
);
CREATE UNIQUE INDEX uq_gp_one_current_per_user ON user_general_practitioners(user_id) WHERE is_current;
CREATE INDEX idx_gp_history_user ON user_general_practitioners(user_id, id DESC);
