CREATE TABLE medical_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,

    name VARCHAR(200) NOT NULL,
    category VARCHAR(30) NOT NULL,

    icon_key VARCHAR(100),

    option_selection_mode VARCHAR(10) NOT NULL DEFAULT 'MULTIPLE',

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_medical_services_category
        CHECK (category IN ('LABORATORY', 'SPECIALIST', 'DIAGNOSTIC', 'SURGICAL', 'THERAPEUTIC')),

    CONSTRAINT chk_medical_services_name_not_blank
        CHECK (LENGTH(BTRIM(name)) > 0),
    
    CONSTRAINT chk_medical_services_option_selection_mode
    CHECK (option_selection_mode IN ('SINGLE', 'MULTIPLE'))
);

CREATE UNIQUE INDEX uq_medical_services_global_name_category
    ON medical_services (LOWER(BTRIM(name)), category)
    WHERE user_id IS NULL;

CREATE UNIQUE INDEX uq_medical_services_user_name_category
    ON medical_services (user_id, LOWER(BTRIM(name)), category)
    WHERE user_id IS NOT NULL;