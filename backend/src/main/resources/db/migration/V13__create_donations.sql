-- Health Diary: eligibility assessments and donations of blood, plasma,
-- platelets, hematopoietic stem cells, or other donation types.
-- Requires V7 (medical_events and facilities). V1/V2 remain unchanged.
CREATE TABLE donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    donation_date DATE NOT NULL,
    record_type VARCHAR(20) NOT NULL,
    donation_type VARCHAR(40),
    medical_event_id BIGINT,
    eligibility_result VARCHAR(20),
    facility_id BIGINT,
    quantity_ml NUMERIC(8,2),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_donations_record_type
        CHECK (record_type IN ('ELIGIBILITY', 'DONATION')),
    CONSTRAINT chk_donations_donation_type
        CHECK (donation_type IS NULL OR donation_type IN
            ('WHOLE_BLOOD', 'PLASMA', 'PLATELETS', 'HEMATOPOIETIC_STEM_CELLS', 'OTHER')),
    CONSTRAINT chk_donations_donation_type_required
        CHECK (record_type <> 'DONATION' OR donation_type IS NOT NULL),
    CONSTRAINT chk_donations_eligibility_result
        CHECK (eligibility_result IS NULL OR eligibility_result IN
            ('ELIGIBLE', 'NOT_ELIGIBLE', 'DEFERRED')),
    CONSTRAINT chk_donations_eligibility_only
        CHECK (record_type = 'ELIGIBILITY' OR eligibility_result IS NULL),
    CONSTRAINT chk_donations_quantity
        CHECK (quantity_ml IS NULL OR quantity_ml > 0),
    CONSTRAINT chk_donations_quantity_only
        CHECK (record_type = 'DONATION' OR quantity_ml IS NULL),
    CONSTRAINT fk_donations_medical_event_owner
        FOREIGN KEY (medical_event_id, user_id)
        REFERENCES medical_events(id, user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_donations_facility_owner
        FOREIGN KEY (facility_id, user_id)
        REFERENCES facilities(id, user_id) ON DELETE RESTRICT
);

CREATE INDEX idx_donations_user_date ON donations(user_id, donation_date DESC);
CREATE INDEX idx_donations_medical_event ON donations(medical_event_id)
    WHERE medical_event_id IS NOT NULL;
