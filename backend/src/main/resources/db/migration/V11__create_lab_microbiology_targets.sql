CREATE TABLE lab_microbiology_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_result_id BIGINT NOT NULL
        REFERENCES exam_results(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    target_name VARCHAR(250) NOT NULL
        CHECK (LENGTH(BTRIM(target_name)) > 0),
    result VARCHAR(20) NOT NULL
        CHECK (result IN ('POSITIVE', 'NEGATIVE', 'INDETERMINATE', 'OTHER')),
    result_text TEXT,
    method VARCHAR(100),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_lab_microbiology_targets_position
        UNIQUE (exam_result_id, position),
    CONSTRAINT chk_lab_microbiology_targets_method_not_blank
        CHECK (method IS NULL OR LENGTH(BTRIM(method)) > 0)
);

CREATE INDEX idx_lab_microbiology_targets_exam_result
    ON lab_microbiology_targets (exam_result_id);
