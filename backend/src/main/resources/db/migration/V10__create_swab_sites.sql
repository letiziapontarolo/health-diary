-- Health Diary: catalogo delle sedi di prelievo per tamponi.
-- Questa migrazione e' autonoma e non presume la struttura delle tabelle degli esami.
-- Eseguire come V8 solo se tale versione non e' gia' utilizzata.

CREATE TABLE swab_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_swab_sites_name_not_blank CHECK (LENGTH(BTRIM(name)) > 0)
);

CREATE UNIQUE INDEX uq_swab_sites_name ON swab_sites (LOWER(BTRIM(name)));

