CREATE TABLE lab_result_organisms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_result_id BIGINT NOT NULL REFERENCES exam_results(id) ON DELETE CASCADE,
    organism_type VARCHAR(20) NOT NULL
        CHECK (organism_type IN ('BACTERIUM', 'FUNGUS', 'PARASITE', 'OTHER')),
    organism_name VARCHAR(250) NOT NULL CHECK (LENGTH(BTRIM(organism_name)) > 0),
    position INTEGER NOT NULL CHECK (position > 0),
    observed_form VARCHAR(150),  -- es. uova, cisti, trofozoiti; soprattutto parassiti
    quantity_numeric NUMERIC(18,6),
    quantity_unit VARCHAR(50),   -- es. UFC/mL, se riportato dal laboratorio
    quantity_text TEXT,          -- es. crescita scarsa, numerosi, rari
    antimicrobial_susceptibility TEXT, -- antibiogramma o antimicogramma testuale
    identification_method VARCHAR(150), -- colturale, microscopia, PCR, ecc.
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_lab_result_organisms_position UNIQUE (exam_result_id, position),
    CONSTRAINT ck_lab_result_organisms_quantity CHECK (
        quantity_numeric IS NULL OR quantity_numeric >= 0
    ),
    CONSTRAINT ck_lab_result_organisms_unit CHECK (
        quantity_unit IS NULL OR LENGTH(BTRIM(quantity_unit)) > 0
    )
);

CREATE INDEX idx_lab_result_organisms_exam_result
    ON lab_result_organisms (exam_result_id);
