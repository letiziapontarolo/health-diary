-- Documents metadata. Actual files are stored outside the database.
CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    original_name VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL
        CHECK (LENGTH(BTRIM(display_name)) > 0),

    storage_key VARCHAR(255) NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL
        CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    file_size BIGINT NOT NULL
        CHECK (file_size > 0 AND file_size <= 26214400),

    category_id BIGINT NOT NULL
        REFERENCES document_categories(id),

    document_date DATE,
    expiry_date DATE,
    notes TEXT,
    is_report BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (id, user_id)
);

CREATE INDEX idx_documents_user_date
    ON documents(user_id, document_date DESC);

CREATE INDEX idx_documents_user_category
    ON documents(user_id, category_id);


-- Many-to-many relationship between documents and medical events.
CREATE TABLE medical_event_documents (
    document_id BIGINT NOT NULL,
    medical_event_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    PRIMARY KEY (document_id, medical_event_id),

    FOREIGN KEY (document_id, user_id)
        REFERENCES documents(id, user_id)
        ON DELETE CASCADE,

    FOREIGN KEY (medical_event_id, user_id)
        REFERENCES medical_events(id, user_id)
        ON DELETE CASCADE
);

CREATE INDEX idx_medical_event_documents_event
    ON medical_event_documents(medical_event_id);
