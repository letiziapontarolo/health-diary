-- Global and user-defined document categories.
CREATE TABLE document_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,

    name VARCHAR(100) NOT NULL
        CHECK (LENGTH(BTRIM(name)) > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_document_categories_global_name
    ON document_categories (LOWER(BTRIM(name)))
    WHERE user_id IS NULL;

CREATE UNIQUE INDEX uq_document_categories_user_name
    ON document_categories (user_id, LOWER(BTRIM(name)))
    WHERE user_id IS NOT NULL;

