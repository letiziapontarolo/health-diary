-- Every result belongs to a laboratory medical event; a parameter may repeat.
CREATE TABLE exam_results (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 exam_id BIGINT NOT NULL REFERENCES medical_events(id) ON DELETE CASCADE,
 parameter_id BIGINT NOT NULL REFERENCES lab_parameters(id) ON DELETE RESTRICT,
 position INTEGER NOT NULL CHECK(position > 0),
 value_type VARCHAR(20) NOT NULL CHECK(value_type IN ('NUMERIC','TEXT','UNAVAILABLE')),
 numeric_value NUMERIC(18,6),
 text_value TEXT,
 unit_id BIGINT REFERENCES measurement_units(id) ON DELETE RESTRICT,
 interval_type VARCHAR(20) CHECK(interval_type IN ('RANGE','LOWER_BOUND','UPPER_BOUND','TEXT')),
 lower_bound NUMERIC(18,6),
 upper_bound NUMERIC(18,6),
 lower_inclusive BOOLEAN,
 upper_inclusive BOOLEAN,
 text_interval TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (exam_id,position),
 CONSTRAINT chk_exam_result_value CHECK (
   (value_type='NUMERIC' AND numeric_value IS NOT NULL AND text_value IS NULL)
   OR (value_type='TEXT' AND numeric_value IS NULL AND text_value IS NOT NULL AND LENGTH(BTRIM(text_value))>0)
   OR (value_type='UNAVAILABLE' AND numeric_value IS NULL AND text_value IS NULL)
 ),
 CONSTRAINT chk_exam_result_unit CHECK (value_type='NUMERIC' OR unit_id IS NULL),
 CONSTRAINT chk_exam_result_interval CHECK (
  (interval_type IS NULL AND lower_bound IS NULL AND upper_bound IS NULL AND lower_inclusive IS NULL AND upper_inclusive IS NULL AND text_interval IS NULL)
  OR (interval_type='RANGE' AND lower_bound IS NOT NULL AND upper_bound IS NOT NULL AND lower_inclusive IS NOT NULL AND upper_inclusive IS NOT NULL AND text_interval IS NULL AND lower_bound<=upper_bound AND (lower_bound<>upper_bound OR (lower_inclusive AND upper_inclusive)))
  OR (interval_type='LOWER_BOUND' AND lower_bound IS NOT NULL AND lower_inclusive IS NOT NULL AND upper_bound IS NULL AND upper_inclusive IS NULL AND text_interval IS NULL)
  OR (interval_type='UPPER_BOUND' AND upper_bound IS NOT NULL AND upper_inclusive IS NOT NULL AND lower_bound IS NULL AND lower_inclusive IS NULL AND text_interval IS NULL)
  OR (interval_type='TEXT' AND text_interval IS NOT NULL AND LENGTH(BTRIM(text_interval))>0 AND lower_bound IS NULL AND upper_bound IS NULL AND lower_inclusive IS NULL AND upper_inclusive IS NULL)
 )
);
CREATE INDEX idx_exam_results_parameter ON exam_results(parameter_id);
