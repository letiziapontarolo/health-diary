-- One medical event is a visit, diagnostic procedure, or laboratory session.
CREATE TABLE doctors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name VARCHAR(200) NOT NULL CHECK (LENGTH(BTRIM(name)) > 0),
 specialization VARCHAR(150),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (id, user_id)
);
CREATE TABLE facilities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name VARCHAR(200) NOT NULL CHECK (LENGTH(BTRIM(name)) > 0),
 city VARCHAR(150),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (id, user_id)
);
CREATE TABLE medical_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 service_id BIGINT NOT NULL REFERENCES medical_services(id) ON DELETE RESTRICT,
 doctor_id BIGINT,
 facility_id BIGINT,
 event_date DATE NOT NULL,
 event_time TIME,
 status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
   CHECK (status IN ('SCHEDULED','COMPLETED','CANCELLED')),
 status_mode VARCHAR(10) NOT NULL DEFAULT 'AUTO'
   CHECK (status_mode IN ('AUTO','MANUAL')),
 report_text TEXT,
 report_not_expected BOOLEAN NOT NULL DEFAULT FALSE,
 notes TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (id,user_id),
 FOREIGN KEY (doctor_id,user_id) REFERENCES doctors(id,user_id) ON DELETE RESTRICT,
 FOREIGN KEY (facility_id,user_id) REFERENCES facilities(id,user_id) ON DELETE RESTRICT
);
CREATE INDEX idx_medical_events_user_date ON medical_events(user_id,event_date DESC);
CREATE INDEX idx_medical_events_service ON medical_events(service_id);
