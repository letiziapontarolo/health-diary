CREATE TABLE lab_parameters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    service_id BIGINT NOT NULL
        REFERENCES medical_services(id) ON DELETE RESTRICT,

    user_id BIGINT
        REFERENCES users(id) ON DELETE CASCADE,

    name VARCHAR(200) NOT NULL,

    group_key VARCHAR(50),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_lab_parameters_name_not_blank
        CHECK (LENGTH(BTRIM(name)) > 0),
    
    CONSTRAINT chk_lab_parameters_group_key CHECK (
    group_key IS NULL OR group_key IN (
        'HEMOGRAM', 'SERUM_PROTEIN_ELECTROPHORESIS', 'COAGULATION_PT',
        'URINALYSIS_CHEMICAL', 'URINE_SEDIMENT', 'URINE_CULTURE',
        'URINE_CYTOLOGY', 'STOOL_MACROSCOPIC', 'STOOL_CULTURE',
        'STOOL_PARASITOLOGY', 'STOOL_FUNGAL_CULTURE',
        'SWAB_CULTURE', 'SWAB_MOLECULAR', 'SWAB_ANTIGEN',
        'SWAB_MICROSCOPY'
    )
)
);

CREATE UNIQUE INDEX uq_lab_parameters_global_name
    ON lab_parameters (service_id, LOWER(BTRIM(name)))
    WHERE user_id IS NULL;

CREATE UNIQUE INDEX uq_lab_parameters_user_name
    ON lab_parameters (service_id, user_id, LOWER(BTRIM(name)))
    WHERE user_id IS NOT NULL;